-- Благодаря триггеру `trg_messages_before_insert`, бэкенду достаточно просто передать
-- `conversation_id`, `parent_id`, `role` и `content`.
-- Триггер сам:
-- 1. Вычислит глубину (depth = parent.depth + 1).
-- 2. Определит branch_index (0 для первого ребенка, 1, 2... для ответвлений).
-- 3. Выставит is_fork = TRUE и fork_point_id = parent_id, если создается ветка.

-- Пример: пользователь смотрит на ответ ИИ #1 и решает создать НОВОЕ (третье) ответвление:
INSERT INTO messages (
    conversation_id,
    parent_id,
    role,
    content,
    metadata
)
VALUES (
    '11111111-1111-1111-1111-111111111111'::uuid,
    'b0000000-0000-0000-0000-000000000001'::uuid, -- Родитель #1
    'user',
    '№6 А какие единицы измерения давления существуют?',
    '{"client": "web", "ui_mode": "branch_split"}'::jsonb
)
RETURNING id, depth, branch_index, is_fork, fork_point_id, created_at;
