-- Назначение: Удаление ветви диалога (поддерева)
-- ============================================================================

-- Так как в схеме таблицы messages для внешнего ключа parent_id указано
-- ON DELETE CASCADE, удаление любой ноды АВТОМАТИЧЕСКИ каскадно удаляет
-- всех её потомков (всё поддерево), не затрагивая родителей и параллельные ветви!

-- Пример: удаляем ветку атмосферного давления (нода №5)
-- При этом ответ #5 удалится автоматически благодаря CASCADE
DELETE FROM messages
WHERE id = 'a0000000-0000-0000-0000-000000000005'::uuid;

-- Родитель #2 и параллельная ветка №3 останутся в целости и сохранности!
