-- Назначение: Получение соседних веток у одной развилки (например, для переключателя
--             «Ветка 1 из 3 < >» в UI, как в классических интерфейсах с ветвлением)
-- ============================================================================

-- Допустим, мы находимся в сообщении №2 ('a0000000-0000-0000-0000-000000000002')
-- и хотим узнать, какие еще есть параллельные вопросы к тому же родителю:
SELECT 
    m.id,
    m.parent_id,
    m.role,
    m.content,
    m.branch_index,
    m.created_at,
    (m.id = 'a0000000-0000-0000-0000-000000000002'::uuid) AS is_current_node,
    COUNT(*) OVER () AS total_siblings
FROM messages m
WHERE m.parent_id = (
    SELECT parent_id 
    FROM messages 
    WHERE id = 'a0000000-0000-0000-0000-000000000002'::uuid
)
ORDER BY m.branch_index ASC, m.created_at ASC;
